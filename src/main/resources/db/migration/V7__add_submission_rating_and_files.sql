ALTER TABLE form_submissions ADD COLUMN rating NUMERIC(2, 1);

CREATE TABLE form_submission_files (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT       NOT NULL,
    field_code    VARCHAR(100) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    stored_path   VARCHAR(500) NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    size_bytes    BIGINT       NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_form_submission_files_submission FOREIGN KEY (submission_id) REFERENCES form_submissions (id) ON DELETE CASCADE,
    CONSTRAINT uk_form_submission_files_submission_field UNIQUE (submission_id, field_code)
);
