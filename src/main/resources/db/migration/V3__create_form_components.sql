CREATE TABLE form_components (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id           BIGINT       NOT NULL,
    field_code        VARCHAR(100) NOT NULL,
    field_label       VARCHAR(255) NOT NULL,
    component_type    VARCHAR(255) NOT NULL,
    placeholder       VARCHAR(255),
    help_text         VARCHAR(500),
    default_value     JSONB,
    display_order     INTEGER      NOT NULL,
    is_required       BOOLEAN      NOT NULL DEFAULT FALSE,
    is_read_only      BOOLEAN      NOT NULL DEFAULT FALSE,
    is_disabled       BOOLEAN      NOT NULL DEFAULT FALSE,
    is_visible        BOOLEAN      NOT NULL DEFAULT TRUE,
    parent_section_id BIGINT,
    properties        JSONB        NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_form_components_form FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE CASCADE,
    CONSTRAINT fk_form_components_parent FOREIGN KEY (parent_section_id) REFERENCES form_components (id) ON DELETE CASCADE,
    CONSTRAINT uk_form_components_form_field_code UNIQUE (form_id, field_code)
);
