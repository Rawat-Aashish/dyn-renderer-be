CREATE TABLE form_validation_rules (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_id  BIGINT       NOT NULL,
    rule_type     VARCHAR(255) NOT NULL,
    rule_value    VARCHAR(500) NOT NULL,
    error_message VARCHAR(500),
    created_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_form_validation_rules_component FOREIGN KEY (component_id) REFERENCES form_components (id) ON DELETE CASCADE,
    CONSTRAINT uk_form_validation_rules_component_type UNIQUE (component_id, rule_type)
);

CREATE TABLE form_conditions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id           BIGINT       NOT NULL,
    target_field_code VARCHAR(100) NOT NULL,
    action            VARCHAR(255) NOT NULL,
    logical_operator  VARCHAR(255) NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_form_conditions_form FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE CASCADE
);

CREATE TABLE form_condition_rules (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condition_id      BIGINT       NOT NULL,
    source_field_code VARCHAR(100) NOT NULL,
    operator          VARCHAR(255) NOT NULL,
    value             VARCHAR(500),
    CONSTRAINT fk_form_condition_rules_condition FOREIGN KEY (condition_id) REFERENCES form_conditions (id) ON DELETE CASCADE
);
