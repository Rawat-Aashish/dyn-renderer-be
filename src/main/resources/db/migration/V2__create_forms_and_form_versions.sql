CREATE TABLE forms (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255) NOT NULL,
    code              VARCHAR(50)  NOT NULL,
    description       TEXT,
    category          VARCHAR(100),
    status            VARCHAR(255) NOT NULL,
    current_version   INTEGER      NOT NULL,
    published_version INTEGER,
    deleted_at        TIMESTAMP(6),
    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_forms_name UNIQUE (name),
    CONSTRAINT uk_forms_code UNIQUE (code)
);

CREATE TABLE form_versions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id        BIGINT       NOT NULL,
    version_number INTEGER      NOT NULL,
    configuration  JSONB,
    status         VARCHAR(255) NOT NULL,
    published_at   TIMESTAMP(6),
    created_at     TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_form_versions_form FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE CASCADE,
    CONSTRAINT uk_form_versions_form_version UNIQUE (form_id, version_number)
);
