CREATE TABLE form_submissions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id         BIGINT       NOT NULL,
    form_version_id BIGINT       NOT NULL,
    token           UUID         NOT NULL,
    status          VARCHAR(255) NOT NULL,
    submitted_data  JSONB,
    started_at      TIMESTAMP(6) NOT NULL,
    submitted_at    TIMESTAMP(6),
    CONSTRAINT fk_form_submissions_form FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE CASCADE,
    CONSTRAINT fk_form_submissions_version FOREIGN KEY (form_version_id) REFERENCES form_versions (id) ON DELETE CASCADE,
    CONSTRAINT uk_form_submissions_token UNIQUE (token)
);

CREATE INDEX idx_form_submissions_form_status ON form_submissions (form_id, status);
