CREATE TABLE form_audit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id        BIGINT       NOT NULL,
    action         VARCHAR(255) NOT NULL,
    version_number INTEGER      NOT NULL,
    user_id        BIGINT       NOT NULL,
    created_at     TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_form_audit_form FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE CASCADE,
    CONSTRAINT fk_form_audit_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_form_audit_form ON form_audit (form_id);
